import type { Proposal } from '@friday/shared';
import { AiError, USER_MESSAGES, type ProviderAdapter, type StreamEvent } from '../types.js';

export interface AssistantContext {
  displayName: string;
  todayTasks: string[];
  nextReminders: string[];
  proposals: Proposal[];
  /** Today's and tomorrow's calendar events. */
  events?: string[];
  /** A stored briefing snapshot the message refers to. */
  briefing?: { label: string; lines: string[]; mainStory: string | null } | null;
}

const sleep = (ms: number, signal: AbortSignal) =>
  new Promise<void>((resolve, reject) => {
    const t = setTimeout(resolve, ms);
    signal.addEventListener('abort', () => {
      clearTimeout(t);
      reject(new AiError('cancelled', USER_MESSAGES.cancelled, undefined, 'demo'));
    }, { once: true });
  });

/** Builds a deterministic reply from real persisted data. Clearly labelled as demo. */
export function demoReply(lastUser: string, ctx: AssistantContext): string {
  const text = lastUser.toLowerCase();
  const prefix = 'Demo mode — no AI provider is connected, so this reply is generated by simple rules.\n\n';
  if (ctx.proposals.length) {
    const p = ctx.proposals[0]!;
    const what = p.kind === 'reminder' ? 'a reminder' : p.kind === 'event' ? 'a calendar event' : 'a task';
    return `${prefix}I can set up ${what} for "${p.title}". Review the details on the card below and tap Confirm to save it — nothing is saved until you do.`;
  }
  if (ctx.briefing) {
    const b = ctx.briefing;
    return `${prefix}From ${b.label}: ${b.mainStory ? `the main story was “${b.mainStory}”.` : 'there were no news stories in it.'}\n\n${b.lines.slice(0, 6).map((l) => `- ${l}`).join('\n')}`;
  }
  if (/\b(task|todo|to-do|plan|today|agenda)\b/.test(text)) {
    if (!ctx.todayTasks.length) return `${prefix}You have no open tasks due today. Want to add one? Try "Add a task to review the budget tomorrow at 10am".`;
    return `${prefix}Here's what's on your plate today:\n${ctx.todayTasks.map((t) => `• ${t}`).join('\n')}`;
  }
  if (/\b(remind|reminder|upcoming)\b/.test(text)) {
    if (!ctx.nextReminders.length) return `${prefix}You have no upcoming reminders. Try "Remind me to call the dentist tomorrow at 5 PM".`;
    return `${prefix}Your next reminders:\n${ctx.nextReminders.map((t) => `• ${t}`).join('\n')}`;
  }
  if (/^(hi|hello|hey|good (morning|afternoon|evening))\b/.test(text)) {
    return `${prefix}Hi ${ctx.displayName}! I can add tasks and reminders, summarise your day, and point you to today's lesson. Connect an AI provider in the server settings for open-ended conversation.`;
  }
  return `${prefix}I understood your message, but open-ended answers need a connected AI provider. Meanwhile I can still create tasks and reminders from phrases like "Remind me to stretch every day at 4pm", and the Tasks, Learn and News tabs work fully.`;
}

export function createDemoAdapter(): ProviderAdapter {
  return {
    id: 'demo',
    model: 'demo-rules',
    pricing: { input: 0, output: 0 },
    async *stream(req): AsyncGenerator<StreamEvent> {
      const last = [...req.messages].reverse().find((m) => m.role === 'user')?.content ?? '';
      const ctx = req.context ?? { displayName: 'there', todayTasks: [], nextReminders: [], proposals: [] };
      const reply = demoReply(last, ctx);
      // Stream word by word so the UI's streaming path is exercised in demo mode too.
      for (const piece of reply.match(/\S+\s*/g) ?? []) {
        await sleep(12, req.signal);
        yield { type: 'text', text: piece };
      }
      yield { type: 'done', usage: { input: 0, output: 0 }, model: 'demo-rules' };
    },
  };
}
